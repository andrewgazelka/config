//! `strata schema import`: a JSON Schema as strata `type` declarations.
//!
//! The subset is what the app schemas in the stdlib use: `type` (one or a
//! list), `properties`, `required`, `additionalProperties` (bool or a
//! schema), `items` (one schema), `enum`, `const`, `anyOf` and `oneOf` (both
//! a union: exclusivity is not checked), `not: {}` inside them (dropped), and
//! `$ref` into `$defs` / `definitions`. Annotations and value constraints
//! (`description`, `default`, `pattern`, `minLength`, `minimum`, `format`,
//! `uniqueItems`, `propertyNames`, ...) are accepted and not checked; any
//! other keyword fails the import, naming where it is.

use serde_json::{Map, Value};

/// Keywords that only annotate or constrain values beyond what strata types say.
const IGNORED: &[&str] = &[
    "$schema",
    "$id",
    "$comment",
    "title",
    "description",
    "markdownDescription",
    "default",
    "examples",
    "deprecated",
    "format",
    "pattern",
    "minLength",
    "maxLength",
    "minimum",
    "maximum",
    "exclusiveMinimum",
    "exclusiveMaximum",
    "multipleOf",
    "minItems",
    "maxItems",
    "uniqueItems",
    "minProperties",
    "maxProperties",
    "propertyNames",
    "allowTrailingCommas",
];

const HANDLED: &[&str] = &[
    "type",
    "properties",
    "required",
    "additionalProperties",
    "items",
    "enum",
    "const",
    "anyOf",
    "oneOf",
    "$ref",
    "$defs",
    "definitions",
];

/// The strata source for `schema`, named `name`; `source` and `hash` go in the header.
pub fn convert(schema: &Value, name: &str, source: &str, hash: &str) -> Result<String, String> {
    let c = Conv { name };
    let mut out = format!(
        "// Generated by `strata schema import {source} --name {name}`.\n\
         // Do not edit: re-run the import. blake3 of the source:\n\
         // {hash}\n\
         //\n\
         // Checked: types, properties, required, additionalProperties, items, enum,\n\
         // const, anyOf/oneOf (as unions). Not checked: patterns, lengths, ranges,\n\
         // formats, uniqueness.\n\n"
    );
    out.push_str(&format!("type {name} = {}\n", c.ty(schema, "#", 0)?));
    for key in ["$defs", "definitions"] {
        if let Some(defs) = schema.get(key).and_then(Value::as_object) {
            for (def, s) in defs {
                out.push_str(&format!("\ntype {} = {}\n", c.alias(def), c.ty(s, &format!("#/{key}/{def}"), 0)?));
            }
        }
    }
    Ok(out)
}

struct Conv<'a> {
    name: &'a str,
}

impl Conv<'_> {
    fn alias(&self, def: &str) -> String {
        format!("{}-{}", self.name, kebab(def))
    }

    fn ty(&self, s: &Value, at: &str, depth: usize) -> Result<String, String> {
        let obj = match s {
            Value::Bool(true) => return Ok("any".into()),
            Value::Object(o) => o,
            _ => return Err(format!("{at}: a schema must be an object or `true`")),
        };
        for k in obj.keys() {
            if !HANDLED.contains(&k.as_str()) && !IGNORED.contains(&k.as_str()) {
                return Err(format!("{at}: unsupported keyword `{k}`"));
            }
        }
        if let Some(r) = obj.get("$ref") {
            let r = r.as_str().ok_or_else(|| format!("{at}: `$ref` must be a string"))?;
            return match r.strip_prefix("#/$defs/").or_else(|| r.strip_prefix("#/definitions/")) {
                Some(def) => Ok(self.alias(def)),
                None if r == "#" => Ok(self.name.to_string()),
                None => Err(format!("{at}: unsupported `$ref` {r:?} (only #/$defs/... and #)")),
            };
        }
        for key in ["anyOf", "oneOf"] {
            if let Some(alts) = obj.get(key) {
                let alts = alts.as_array().ok_or_else(|| format!("{at}: `{key}` must be a list"))?;
                let mut terms = Vec::new();
                for (i, alt) in alts.iter().enumerate() {
                    // `not: {}` matches nothing: a union member that adds nothing.
                    if alt.get("not").is_some_and(|n| n.as_object().is_some_and(Map::is_empty)) {
                        continue;
                    }
                    if alt.get("not").is_some() {
                        return Err(format!("{at}/{key}/{i}: unsupported `not`"));
                    }
                    terms.push(self.ty(alt, &format!("{at}/{key}/{i}"), depth)?);
                }
                return Ok(union(terms));
            }
        }
        if let Some(c) = obj.get("const") {
            return Ok(literal(c));
        }
        if let Some(e) = obj.get("enum") {
            let e = e.as_array().ok_or_else(|| format!("{at}: `enum` must be a list"))?;
            return Ok(union(e.iter().map(literal).collect()));
        }
        match obj.get("type") {
            None if obj.contains_key("properties") || obj.contains_key("additionalProperties") => {
                self.object(obj, at, depth)
            }
            None => Ok("any".into()),
            Some(Value::String(t)) => self.typed(t, obj, at, depth),
            Some(Value::Array(ts)) => {
                let terms = ts
                    .iter()
                    .map(|t| match t {
                        Value::String(t) => self.typed(t, obj, at, depth),
                        _ => Err(format!("{at}: `type` lists names")),
                    })
                    .collect::<Result<_, _>>()?;
                Ok(union(terms))
            }
            Some(_) => Err(format!("{at}: `type` must be a name or a list of names")),
        }
    }

    fn typed(&self, t: &str, obj: &Map<String, Value>, at: &str, depth: usize) -> Result<String, String> {
        Ok(match t {
            "string" => "string".into(),
            "integer" => "int".into(),
            "number" => "number".into(),
            "boolean" => "bool".into(),
            "null" => "null".into(),
            "array" => match obj.get("items") {
                None => "list(any)".into(),
                Some(Value::Array(_)) => return Err(format!("{at}: tuple `items` is unsupported")),
                Some(items) => format!("list({})", self.ty(items, &format!("{at}/items"), depth)?),
            },
            "object" => self.object(obj, at, depth)?,
            other => return Err(format!("{at}: unknown type {other:?}")),
        })
    }

    fn object(&self, obj: &Map<String, Value>, at: &str, depth: usize) -> Result<String, String> {
        let rest = match obj.get("additionalProperties") {
            None | Some(Value::Bool(true)) => Some("any".to_string()),
            Some(Value::Bool(false)) => None,
            Some(s) => Some(self.ty(s, &format!("{at}/additionalProperties"), depth + 1)?),
        };
        let props = obj.get("properties").and_then(Value::as_object).filter(|p| !p.is_empty());
        let Some(props) = props else {
            return Ok(match rest {
                None => "{}".into(),
                Some(t) => format!("map({t})"),
            });
        };
        let required: Vec<&str> =
            obj.get("required").and_then(Value::as_array).into_iter().flatten().filter_map(Value::as_str).collect();
        let pad = "    ".repeat(depth + 1);
        let mut out = String::from("{\n");
        for (key, s) in props {
            if let Some(d) = s.get("description").and_then(Value::as_str).map(first_sentence) {
                out.push_str(&format!("{pad}// {d}\n"));
            }
            let opt = if required.contains(&key.as_str()) { "" } else { "?" };
            let t = self.ty(s, &format!("{at}/properties/{key}"), depth + 1)?;
            out.push_str(&format!("{pad}{}{opt}: {t}\n", field_name(key)));
        }
        match rest {
            None => {}
            Some(t) if t == "any" => out.push_str(&format!("{pad}..\n")),
            Some(t) => out.push_str(&format!("{pad}..: {t}\n")),
        }
        out.push_str(&"    ".repeat(depth));
        out.push('}');
        Ok(out)
    }
}

/// A description's first sentence, for a one-line comment.
fn first_sentence(d: &str) -> &str {
    let line = d.lines().next().unwrap_or_default().trim_end();
    match line.find(". ") {
        Some(i) => &line[..=i],
        None => line,
    }
}

fn union(mut terms: Vec<String>) -> String {
    terms.dedup();
    match terms.len() {
        0 => "any".into(),
        1 => terms.pop().unwrap(),
        // Parenthesized so a union nests inside list(...) or another union.
        _ => format!("({})", terms.join(" | ")),
    }
}

/// A string is a literal type; strata has no other literal types, so other
/// constants check as their kind.
fn literal(v: &Value) -> String {
    match v {
        Value::String(s) => quote(s),
        Value::Bool(_) => "bool".into(),
        Value::Number(n) if n.is_i64() || n.is_u64() => "int".into(),
        Value::Number(_) => "number".into(),
        Value::Null => "null".into(),
        Value::Array(_) => "list(any)".into(),
        Value::Object(_) => "map(any)".into(),
    }
}

fn quote(s: &str) -> String {
    let mut out = String::from("\"");
    for c in s.chars() {
        match c {
            '"' => out.push_str("\\\""),
            '\\' => out.push_str("\\\\"),
            '$' => out.push_str("\\$"),
            '\n' => out.push_str("\\n"),
            '\r' => out.push_str("\\r"),
            '\t' => out.push_str("\\t"),
            c => out.push(c),
        }
    }
    out.push('"');
    out
}

/// A key as written in a record type: bare when the lexer reads it as one name.
fn field_name(key: &str) -> String {
    let mut chars = key.chars();
    let bare = chars.next().is_some_and(|c| c.is_ascii_alphabetic() || c == '_')
        && chars.all(|c| c.is_ascii_alphanumeric() || c == '_' || c == '-')
        && !key.ends_with('-');
    if bare { key.to_string() } else { quote(key) }
}

/// `permissionRule` -> `permission-rule`.
fn kebab(s: &str) -> String {
    let mut out = String::new();
    let mut prev_lower = false;
    for c in s.chars() {
        if c.is_ascii_uppercase() && prev_lower {
            out.push('-');
        }
        prev_lower = c.is_ascii_lowercase() || c.is_ascii_digit();
        if c.is_ascii_alphanumeric() {
            out.push(c.to_ascii_lowercase());
        } else if !out.ends_with('-') {
            out.push('-');
        }
    }
    out.trim_matches('-').to_string()
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::syntax::ast::Stmt;
    use crate::types::Ty;
    use std::collections::BTreeMap;

    /// The import parses back, and the types refuse what the schema refuses.
    #[test]
    fn import_round_trips_and_checks() {
        let schema = serde_json::json!({
            "$defs": { "rule": { "type": "string" } },
            "type": "object",
            "properties": {
                "statusLine": {
                    "type": "object",
                    "additionalProperties": false,
                    "required": ["type"],
                    "properties": { "type": { "const": "command" }, "padding": { "type": "integer" } }
                },
                "$schema": { "type": "string" },
                "allow": { "type": "array", "items": { "$ref": "#/$defs/rule" } },
                "env": { "type": "object", "additionalProperties": { "type": "string" } },
                "plugins": { "additionalProperties": { "anyOf": [{ "type": "boolean" }, { "not": {} }] } },
                "mode": { "type": ["string", "null"], "enum": ["a", "b$"] }
            }
        });
        let text = convert(&schema, "t", "x.json", "00").unwrap();
        let stmts = crate::syntax::parser::parse(&text, 0).unwrap();
        let mut aliases = BTreeMap::new();
        for s in &stmts {
            let Stmt::TypeDecl { name, ty, .. } = s else { panic!("only types: {s:?}") };
            aliases.insert(name.name.to_string(), ty.clone());
        }
        let ty = Ty::from_expr(&aliases["t"], &aliases).unwrap();
        let v = |j: serde_json::Value| crate::value::Value::from(&j);
        let ok = serde_json::json!({
            "statusLine": { "type": "command" }, "allow": ["Read"], "env": { "A": "1" },
            "plugins": { "p": true }, "mode": "b$", "other": 1
        });
        assert_eq!(ty.check_path(&v(ok)), Ok(()));
        let typo =
            ty.check_path(&v(serde_json::json!({ "statusLine": { "type": "command", "paddin": 1 } }))).unwrap_err();
        assert_eq!(typo.at, ["statusLine", "paddin"]);
        assert!(typo.message.contains("did you mean `padding`"), "{}", typo.message);
        assert!(ty.check_path(&v(serde_json::json!({ "env": { "A": 1 } }))).is_err());
        assert!(ty.check_path(&v(serde_json::json!({ "statusLine": { "type": "cmd" } }))).is_err());
        assert!(convert(&serde_json::json!({ "allOf": [] }), "t", "x", "0").unwrap_err().contains("allOf"));
    }
}
